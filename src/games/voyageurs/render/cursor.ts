/** `setMouseCursor` : décodage d'un curseur. */
function decode(bitmap: readonly number[], hotspotX: number, hotspotY: number): CursorImage {
  const pixels = new Uint8Array(CURSOR_SIZE * CURSOR_SIZE);
  for (let i = 0; i < 32; i++) {
    for (let bit = 0; bit < 8; bit++) {
      const m = 0x80 >> bit;
      pixels[i * 8 + bit] = bitmap[i]! & m ? 1 : bitmap[i + 32]! & m ? 0 : CURSOR_TRANSPARENT;
    }
  }
  return { hotspotX, hotspotY, pixels };
}

/** `mouseCursors`, dans l'ordre de `CursorKind`. */
export const CURSORS: readonly CursorImage[] = [decode(NORMAL, 1, 1), decode(DISK, 0, 0), decode(CROSS, 7, 7)];

/** Curseur de la boucle principale : flèche sans verbe, croix quand un verbe attend son objet. */
export function cursorForCommand(playerCommand: number): CursorImage {
  return CURSORS[playerCommand === -1 ? CursorKind.Normal : CursorKind.Cross]!;
}
