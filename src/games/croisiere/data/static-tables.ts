/** Valeur d'un pixel transparent de `cursorPixels`. */
export const CURSOR_TRANSPARENT = 0xff;

/** Curseur en 16x16 index (`mouse.cpp::changeCursor`). */
export function cursorPixels(cursor: CursorDef): Uint8Array {
  const out = new Uint8Array(256);
  for (let i = 0; i < 32; i++) {
    const shape = cursor.bitmap[i]!;
    const outline = cursor.bitmap[32 + i]!;
    for (let bit = 0; bit < 8; bit++) {
      const mask = 0x80 >> bit;
      out[i * 8 + bit] = shape & mask ? 1 : outline & mask ? 0 : CURSOR_TRANSPARENT;
    }
  }
  return out;
}

