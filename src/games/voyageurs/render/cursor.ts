/**
 * Curseurs de la souris : trois images 16 × 16 monochromes codées en dur (flèche, disquette, croix) et leur point chaud.
 *
 * Référence : ScummVM engines/cine/gfx.cpp (`mouseCursorNormal`, `mouseCursorDisk`, `mouseCursorCross`, `mouseCursors`, `cursorPalette`,
 * `setMouseCursor`) et main_loop.cpp (croix quand un verbe est choisi) (GPL v3 ou ultérieure). docs/voyageurs/engine.md § 3.
 *
 * Chaque curseur tient en 64 octets : 32 octets de dessin (16 lignes de 2 octets, bit de poids fort à gauche) puis 32 octets de contour.
 * Pixel : dessin → blanc (1), sinon contour → noir (0), sinon transparent (`CURSOR_TRANSPARENT`). Données pour l'interface : le rendu de
 * l'écran ne dessine pas le curseur (le banc capture l'image sans lui).
 */

export const CURSOR_SIZE = 16;
/** Valeur d'un pixel transparent. */
export const CURSOR_TRANSPARENT = 0xff;
/** `cursorPalette` : 0 noir, 1 blanc. */
export const CURSOR_PALETTE: readonly (readonly [number, number, number])[] = [
  [0, 0, 0],
  [0xff, 0xff, 0xff],
];

export const CursorKind = { Normal: 0, Disk: 1, Cross: 2 } as const;

export interface CursorImage {
  readonly hotspotX: number;
  readonly hotspotY: number;
  /** 16 × 16 pixels : 0 noir, 1 blanc, `CURSOR_TRANSPARENT`. */
  readonly pixels: Uint8Array;
}

